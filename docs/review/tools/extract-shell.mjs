// docs/review/tools/extract-shell.mjs · copies the shell's own CSS and chrome markup out of the running app into
// docs/review/html/shell/, so the HTML mock-ups draw with the app's own rules rather than an imitation of them.
import fs from 'fs';
import path from 'path';
import { browser, open, OUT } from './harness.mjs';
const b = await browser();
const p = await open(b, '/vendor/rooms', { mode: 'dark' });
const got = await p.evaluate(() => {
  const wl = document.querySelector('.wl');
  const css = [...wl.querySelectorAll('style')].map((s) => s.textContent).join('\n');
  const strip = (el) => { const c = el.cloneNode(true); c.querySelectorAll('style').forEach((s) => s.remove()); return c.outerHTML; };
  return { css, header: strip(document.querySelector('.wl-hdr')), nav: strip(document.querySelector('.wl-nav')),
    dock: strip(document.querySelector('.wl-dockfield').closest('.wl-dock') || document.querySelector('.wl-dockfield').parentElement),
    roomhead: strip(document.querySelector('.wl-roomhead')), wlStyle: wl.getAttribute('style') || '' };
});
const dir = path.join(OUT, 'html/shell');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'shell.css'), '/* copied from the running app by docs/review/tools/extract-shell.mjs: the shell\'s own <style> (theme.ts scopeCss + typeCss, WorklistShell SHELL_CSS, PageHelp) */\n' + got.css);
fs.writeFileSync(path.join(dir, 'chrome.json'), JSON.stringify({ header: got.header, nav: got.nav, dock: got.dock, roomhead: got.roomhead, wlStyle: got.wlStyle }, null, 1));
// the same, as a script, so the mock-ups open from file:// with no server (a browser will not fetch JSON there)
fs.writeFileSync(path.join(dir, 'chrome.js'), '// generated by docs/review/tools/extract-shell.mjs\nwindow.TDW_CHROME = ' + JSON.stringify({ header: got.header, nav: got.nav, dock: got.dock, roomhead: got.roomhead, wlStyle: got.wlStyle }) + ';\n');
console.log('css', got.css.length, 'header', got.header.length, 'nav', got.nav.length, 'dock', got.dock.length);
await b.close();
